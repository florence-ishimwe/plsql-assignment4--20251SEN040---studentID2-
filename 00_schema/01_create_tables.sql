-- 1. Customers Table
CREATE TABLE bank_customers (
    customer_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR2(50) NOT NULL,
    last_name     VARCHAR2(50) NOT NULL,
    email         VARCHAR2(100) UNIQUE NOT NULL,
    phone         VARCHAR2(20),
    created_date  DATE DEFAULT SYSDATE
);

-- 2. Accounts Table
CREATE TABLE bank_accounts (
    account_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   NUMBER NOT NULL,
    account_type  VARCHAR2(20) CHECK (account_type IN ('SAVINGS', 'CHECKING')),
    balance       NUMBER(12, 2) DEFAULT 0.00 CHECK (balance >= 0),
    status        VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    CONSTRAINT fk_cust_account FOREIGN KEY (customer_id) REFERENCES bank_customers(customer_id)
);

-- 3. Transactions Table (Used for Bulk Processing & Audit)
CREATE TABLE bank_transactions (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       NUMBER NOT NULL,
    transaction_type VARCHAR2(20) CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    amount           NUMBER(12, 2) NOT NULL,
    transaction_date DATE DEFAULT SYSDATE,
    status           VARCHAR2(20) DEFAULT 'SUCCESS',
    error_message    VARCHAR2(255),
    CONSTRAINT fk_acc_transaction FOREIGN KEY (account_id) REFERENCES bank_accounts(account_id)
);

COMMIT;
